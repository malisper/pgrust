const fn tk(token: &[u8], typ: i32, value: i32) -> DateTkn {
    let mut t = [0u8; TOKMAXLEN + 1];
    let mut i = 0;
    while i < token.len() {
        t[i] = token[i];
        i += 1;
    }
    DateTkn { token: t, typ: typ as i8, value }
}

