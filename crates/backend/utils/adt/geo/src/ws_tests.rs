fn geo_in_whitespace_matches_c_locale_isspace() {
    let ctx = MemoryContext::new("t");
    let mut bad = Vec::new();
    for &(id, typ, pos, ws, input, expected) in CASES {
        let got = roundtrip(&ctx, typ, input).ok();
        let want = expected.map(str::to_string);
        if got != want {
            bad.push(format!(
                "  #{id} {typ}/{pos}/{ws}: want {want:?}, got {got:?}"
            ));
        }
    }
    assert!(bad.is_empty(), "{} case(s) diverge from C:\n{}", bad.len(), bad.join("\n"));
}

/// The predicate itself.  C-locale isspace is {HT,LF,VT,FF,CR,SP}; VT is the
/// byte Rust's `is_ascii_whitespace` drops, and it is load-bearing above.
#[test]
fn isspace_c_locale_includes_vt() {
    for b in 0u8..=255 {
        let want = matches!(b, b' ' | 0x09..=0x0d);
        assert_eq!(::pg_string::isspace_c_locale(b), want, "byte 0x{b:02x}");
    }
    assert!(::pg_string::isspace_c_locale(0x0b));
    assert!(!0x0bu8.is_ascii_whitespace());
    // The non-ASCII negative controls above are single bytes of a UTF-8
    // sequence; no byte of either is C-locale whitespace.
    for &b in "\u{a0}\u{85}".as_bytes() {
        assert!(!::pg_string::isspace_c_locale(b), "byte 0x{b:02x}");
    }
}
