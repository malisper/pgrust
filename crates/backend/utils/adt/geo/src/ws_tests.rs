//! C-locale whitespace conformance for every geo input function.
//!
//! geo_ops.c asks "is this whitespace?" through `isspace((unsigned char) *p)`
//! at 12 call sites, all of which pgrust routes through `Cursor::ws_end`.  In
//! the C locale that predicate is exactly {HT, LF, VT, FF, CR, SP}; Rust's
//! `u8::is_ascii_whitespace` omits VT (0x0b) and `char::is_whitespace` also
//! over-accepts non-ASCII space code points, so neither may stand in for it.
//!
//! GENERATED from the same source as the SQL differential (see the lane notes)
//! and every expectation below is the verbatim result of executing real
//! PostgreSQL 18.4 (docker postgres:18.4, UTF8/C locale) on the identical
//! byte string, control bytes delivered via chr().
#![allow(clippy::type_complexity)]

use ::mcx::MemoryContext;

use crate::{io, PathRef, PolyRef};

/// `Ok(text)` == C accepted and `typeout` produced `text`; `Err` == C raised
/// "invalid input syntax" / "invalid line specification".
fn roundtrip(ctx: &MemoryContext, typ: &str, s: &str) -> Result<String, ()> {
    let mut out = Vec::new();
    match typ {
        "point" => io::point_out(&io::point_in(s, None).map_err(|_| ())?, &mut out),
        "box" => io::box_out(&io::box_in(s, None).map_err(|_| ())?, &mut out),
        "lseg" => io::lseg_out(&io::lseg_in(s, None).map_err(|_| ())?, &mut out),
        "line" => io::line_out(&io::line_in(s, None).map_err(|_| ())?, &mut out),
        "circle" => io::circle_out(&io::circle_in(s, None).map_err(|_| ())?, &mut out),
        "path" => {
            let v = io::path_in(ctx.mcx(), s, None).map_err(|_| ())?;
            io::path_out(&PathRef::from_payload(v.data()), &mut out).map_err(|_| ())?;
        }
        "polygon" => {
            let v = io::poly_in(ctx.mcx(), s, None).map_err(|_| ())?;
            io::poly_out(&PolyRef::from_payload(v.data()), &mut out).map_err(|_| ())?;
        }
        _ => unreachable!(),
    }
    Ok(String::from_utf8(out).unwrap())
}

