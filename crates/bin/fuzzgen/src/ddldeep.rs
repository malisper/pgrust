    fn gen_groups(seed: u64, n: usize) -> Vec<Vec<String>> {
        let cat = FixtureCatalog.load_catalog().unwrap();
        let w = WeightTable::defaults();
        let mut rng = Rng::new(seed);
        let mut out = Vec::new();
        for _ in 0..n {
            let mut prods = Vec::new();
            let mut g = Gen::new(&mut rng, &cat, &w, &mut prods, 3);
            let stmts = gen_ddldeep_module(&mut g);
            out.push(
                stmts
                    .into_iter()
                    .map(|s| match s {
                        StmtKind::Raw(t) => t,
                        other => panic!("ddldeep emits Raw only, got {other:?}"),
                    })
                    .collect(),
            );
        }
        out
    }

    /// Same seed, same stream — the reproducibility witness.
    #[test]
    fn deterministic_by_seed() {
        assert_eq!(gen_groups(42, 100), gen_groups(42, 100));
    }

    /// Every shape is reachable from the default weight table.
    #[test]
    fn all_shapes_fire() {
        let cat = FixtureCatalog.load_catalog().unwrap();
        let w = WeightTable::defaults();
        let mut rng = Rng::new(7);
        let mut seen = std::collections::HashSet::new();
        for _ in 0..3000 {
            let mut prods = Vec::new();
            let mut g = Gen::new(&mut rng, &cat, &w, &mut prods, 3);
            gen_ddldeep_module(&mut g);
            for p in prods {
                seen.insert(p);
            }
        }
        for shape in SHAPES {
            assert!(seen.contains(*shape), "shape never fired: {shape}");
        }
    }

