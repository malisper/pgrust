//! DDL-deep drain module (lane SQLcov-A; line-drain queue chunks
//! `ddl-cmds-residue` + `ddl-tablecmds` — the residue the LD6/LD8
//! ERROR-ARM waves left; see docs/fuzzing/findings-sqlcov-a.md).
//!
//! Charter shift vs `earm`/`earm2`: the remaining unhit mass is mostly
//! FUNCTIONAL lifecycles, not error fuel — successful AT_* passes
//! (rewrites with USING, identity/generated surgery, storage/compression,
//! cluster/access-method/logged-ness, replica identity, RLS), FK-bearing
//! partition trees through attach/detach/alter cycles
//! (CloneFkReferencing, CloneRowTriggersToPartition, ATPostAlterTypeParse,
//! concurrent detach), partitioned-index attach lifecycles, matview
//! refresh, extended statistics, in-place tablespaces
//! (allow_in_place_tablespaces) and committed rewrite brackets that fuel
//! smgrDoPendingSyncs under a wal_level=minimal profile arm. Deliberate
//! error arms remain where the residue is an ereport (compression method,
//! FK-violating detach, unsafe enum use, CIC duplicate-key), and the
//! differential bar for those stays the ERROR IDENTITY.
//!
//! Rules (inherited from earm2, LD8):
//!   - every group is SELF-CONTAINED and emitted VERBATIM from the
//!     hand-verified deck (fuzz/deck-sqa-ddl.sql, applied per-statement
//!     to the A/B pair before encoding — identical SQLSTATE everywhere;
//!     the two banked message-identity findings SQLCOVA-F1/F2 are
//!     DETAIL-field/NOTICE-code drift the differ does not flag);
//!   - fixtures live under fixed `dd_` names, created and dropped inside
//!     the group; order-sensitive spans (BEGIN brackets, CIC leftovers,
//!     detach-then-attach cycles, SET/RESET GUC pairs) stay intact;
//!   - roles are cluster-global: every CREATE ROLE has its DROP in the
//!     same section past the probes that need it; SET ROLE always has a
//!     later RESET ROLE;
//!   - GUC-touching spans (session_replication_role, row_security,
//!     default_tablespace, allow_in_place_tablespaces) RESET in-section
//!     so the session pin is never poisoned for later groups;
//!   - no result set exposes a user-type column OID (LD8 trap): enum and
//!     range probes cast through ::text.

