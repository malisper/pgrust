//! ERROR-ARM drain module, round 2 (LD8; line-drain queue chunks
//! `ddl-cmds-residue` + `parser-arms` + `catalog-residue` + `ddl-tablecmds`,
//! the residue LD6's `earm` pass left — see docs/fuzzing/findings-ld8.md).
//!
//! Same charter as `earm`: the unhit mass is ereport(ERROR)/validation
//! arms only invalid input reaches, so every probe deliberately errors and
//! the differential bar is the ERROR IDENTITY (SQLSTATE via diff::classify,
//! message drift carried in the detail). Round-2 surface: tablecmds
//! partition/inheritance/FK-clone/attach-detach arms, ALTER COLUMN TYPE,
//! DefineType I/O-function combos, function/operator DDL + resolution,
//! window/agg frame validation, extension + tsearch DDL, shared-dependency
//! drops (pg_shdepend), sequence/identity/generated columns, trigger/rule/
//! constraint definition, encoding/conversion/collation errors, parser
//! residue (U& escapes, literal junk), async/NOTIFY arms, and
//! relation/target-list analysis errors.
//!
//! Rules (inherited from earm, LD6):
//!   - every group is SELF-CONTAINED and emitted VERBATIM from the
//!     hand-verified deck (fuzz/deck-ld8-earm2.sql, applied per-statement
//!     to the A/B pair before encoding — identical SQLSTATE everywhere,
//!     with exactly the four banked identity findings LD8-F1..F2 +
//!     LD6-F1/F2-class recurrences, all SQLSTATE-matched). Verbatim
//!     emission (no sampling) keeps every group byte-identical to the
//!     verified transcript; group size is priced by the module weight;
//!   - fixtures live under fixed `ea2_` names, created and dropped inside
//!     the group; erroring probes cannot create state; the documented
//!     intentional successes are all dropped in-group;
//!   - order-sensitive spans (BEGIN/DETACH CONCURRENTLY/ROLLBACK, the
//!     failed-PREPARE ROLLBACK normalizers, the ALTER EXTENSION ADD/DROP
//!     pair, conversion create/drop pairs) must stay intact — another
//!     reason the sections are verbatim;
//!   - probes embedding assigned OIDs in the DETAIL (enum 23505,
//!     pg_ts_config_map 23505) are SQLSTATE-matched by the differ; the
//!     OID drift is environment, never a finding (LD6-N1 precedent);
//!   - roles are cluster-global: every CREATE ROLE has its DROP in the
//!     same section past the probes that need it;
//!   - GUC-touching spans (search_path, client_encoding) RESET in-section
//!     so the session pin is never poisoned for later groups.

//!
//! Wave 2 (earm2b, deck fuzz/deck-ld8-earm2b.sql, hand-verified the same
//! way — 2 divergent transcript lines, both LD6-F1 errposition-omission
//! recurrences): aclcheck_error per-objtype no-priv/not-owner arms under
//! an unprivileged role, DefineType full base-type + validation arms,
//! CreateRole/AlterRole option matrix, DefineAggregate/AggregateCreate
//! (moving/serial/ordered-set/hypothetical + error combos), aggregate/
//! window/SRF placement-context arms (parse_agg/parse_func EXPR_KIND
//! switches), str_udeescape U& escapes, transformColumnRef qualified-name
//! arms, transformIndexConstraint USING INDEX / WITHOUT OVERLAPS +
//! DefineIndex am-capability arms, and the anycompatible/anyrange/
//! anymultirange residue of enforce_generic_type_consistency.

