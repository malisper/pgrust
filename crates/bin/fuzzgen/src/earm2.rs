fn raw(s: impl Into<String>) -> StmtKind {
    StmtKind::Raw(s.into())
}

fn raws(list: &[&str]) -> Vec<StmtKind> {
    list.iter().map(|s| raw(*s)).collect()
}

/// Shared `ea2_base`/`ea2_ref` fixture pair (the deck's fixtures header):
/// created before and dropped after every section that references them.
fn fx() -> Vec<StmtKind> {
    raws(&[
        "CREATE TABLE ea2_base (a int PRIMARY KEY, b text, c numeric(10,2));",
        "INSERT INTO ea2_base VALUES (1, 'one', 1.10), (2, 'two', 2.20);",
        "CREATE TABLE ea2_ref (x int, y int);",
        "INSERT INTO ea2_ref VALUES (1, 1), (2, 2);",
    ])
}

fn fx_drop() -> Vec<StmtKind> {
    raws(&["DROP TABLE ea2_ref;", "DROP TABLE ea2_base;"])
}

