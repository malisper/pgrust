//! Parser rare-grammar + analysis-arm drain module (SQLcov-B; line-drain
//! queue chunk `parser-arms`, 297 fns / 2,522 hollow lines after LD6+LD8 —
//! see docs/fuzzing/line-gap-report-003.md). The residue is (a) rarer
//! gram.y productions the default statement mix never renders (WITH
//! ORDINALITY, XMLTABLE/JSON_TABLE column-definition grammar, GROUPING
//! SETS/CUBE/ROLLUP nesting, LATERAL variants, window frame-clause
//! grammar, MERGE arms, COPY option grammar, CREATE STATISTICS kinds,
//! partition bound grammar, typecast/collate grammar, operator/aggregate
//! definition grammar, row/array/subscript expression grammar) and (b)
//! transform*.c analysis branches, both success arms fed by those rare
//! forms and ereport arms fed by NEAR-VALID statements that fail in
//! parse analysis (the chunk's bucket is ERROR-ARM).
//!
//! Differential bar: result-set identity for the valid forms, ERROR
//! IDENTITY (SQLSTATE via diff::classify) for the deliberate failures —
//! a parse/analysis divergence on valid syntax or a wrong error class is
//! a real bug (rig law).
//!
//! Rules (earm/numx discipline):
//!   - every group is SELF-CONTAINED: fixtures live under fixed `fz_pg_*`
//!     names, created and dropped in the same group; erroring probes
//!     never create state; a group never leaves GUC or txn state behind
//!     (writes sit in BEGIN..ROLLBACK brackets; no SETs at all);
//!   - every row-returning valid probe carries a total ORDER BY (or is a
//!     single-row scalar SELECT); integer/text data only, generated by
//!     pure row-number formulas — identical on both sides;
//!   - XML runtime probes are expected to raise 0A000 on BOTH engines
//!     (both builds are libxml-less; parity-honest degradation ruling):
//!     the value is the transformXmlTable/transformXmlExpr analysis arms
//!     that run BEFORE execution, and the 0A000 identity itself.

use crate::stmt::{Gen, StmtKind};

fn raw(s: impl Into<String>) -> StmtKind {
    StmtKind::Raw(s.into())
}

fn raws(list: &[&str]) -> Vec<StmtKind> {
    list.iter().map(|s| raw(*s)).collect()
}

fn pick_str<'x>(g: &mut Gen, opts: &[&'x str]) -> &'x str {
    opts[g.rng.below_usize(opts.len())]
}

