/// transformPLAssignStmt arms: plpgsql assignment statements are parsed
/// through the dedicated RAW_PARSE_PLPGSQL_ASSIGN path — subscripted,
/// field-qualified and nested targets each take their own branch.
fn gen_plassign(g: &mut Gen) -> Vec<StmtKind> {
    let _ = g;
    raws(&[
        "CREATE TYPE fz_pg_pa_t AS (u int4, arr int4[]);",
        "DO $$ DECLARE x int4; BEGIN x := 1 + 2; x := x * 3; \
         IF x <> 9 THEN RAISE EXCEPTION 'bad %', x; END IF; END $$;",
        "DO $$ DECLARE a int4[]; BEGIN a := ARRAY[1, 2, 3]; a[2] := 9; \
         a[5] := 7; a[2:3] := ARRAY[4, 5]; \
         IF a <> ARRAY[1,4,5,NULL,7] THEN RAISE EXCEPTION 'bad %', a; END IF; END $$;",
        "DO $$ DECLARE m int4[][]; BEGIN m := ARRAY[ARRAY[1,2],ARRAY[3,4]]; \
         m[1][2] := 9; IF m[1][2] <> 9 THEN RAISE EXCEPTION 'bad'; END IF; END $$;",
        "DO $$ DECLARE r fz_pg_pa_t; BEGIN r.u := 5; r.arr := ARRAY[1]; \
         r.arr[3] := 8; IF r.u + r.arr[3] <> 13 THEN RAISE EXCEPTION 'bad %', r; END IF; END $$;",
        "DO $$ DECLARE r fz_pg_pa_t; s text; BEGIN \
         SELECT 1, ARRAY[2] INTO r.u, r.arr; s := format('%s+%s', r.u, r.arr[1]); \
         IF s <> '1+2' THEN RAISE EXCEPTION 'bad %', s; END IF; END $$;",
        "DO $$ DECLARE x int4; BEGIN x := (SELECT count(*)::int4 FROM (VALUES (1), (2)) v);\
         IF x <> 2 THEN RAISE EXCEPTION 'bad %', x; END IF; END $$;",
        "DO $$ DECLARE a int4[]; b int4; BEGIN a := ARRAY[1,2,3]; \
         b := a[array_lower(a, 1)] + a[array_upper(a, 1)]; \
         IF b <> 4 THEN RAISE EXCEPTION 'bad %', b; END IF; END $$;",
        // Error arms: bad subscript type, field of non-composite,
        // wrong-arity SELECT INTO handled at runtime, unknown field.
        "DO $$ DECLARE a int4[]; BEGIN a['x'] := 1; END $$;",
        "DO $$ DECLARE x int4; BEGIN x.f := 1; END $$;",
        "DO $$ DECLARE r fz_pg_pa_t; BEGIN r.nosuch := 1; END $$;",
        "DO $$ DECLARE x int4; BEGIN x := 'not-an-int'; END $$;",
        "DROP TYPE fz_pg_pa_t;",
    ])
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::catalog::{CatalogSource, FixtureCatalog};
    use crate::rng::Rng;
    use crate::weights::WeightTable;

    fn gen_groups(seed: u64, n: usize) -> Vec<Vec<String>> {
        let cat = FixtureCatalog.load_catalog().unwrap();
        let weights = WeightTable::defaults();
        let mut rng = Rng::new(seed);
        let mut productions = Vec::new();
        let mut out = Vec::new();
        let mut g = Gen::new(&mut rng, &cat, &weights, &mut productions, 4);
        for _ in 0..n {
            let stmts = gen_pgram_module(&mut g);
            out.push(stmts.iter().map(|s| s.to_sql()).collect());
        }
        out
    }

    #[test]
    fn groups_are_txn_balanced_and_guc_clean() {
        // pgram never emits SET/RESET at all (no GUC state to poison),
        // and every BEGIN closes with ROLLBACK in the same group.
        for group in gen_groups(17, 300) {
            let mut open_txn = 0i32;
            for sql in &group {
                assert!(
                    !sql.starts_with("SET ") && !sql.starts_with("RESET "),
                    "pgram must not touch GUCs: {sql}"
                );
                if sql == "BEGIN;" {
                    open_txn += 1;
                } else if sql == "ROLLBACK;" {
                    open_txn -= 1;
                }
            }
            assert_eq!(open_txn, 0, "unclosed BEGIN in {group:?}");
        }
    }

    #[test]
    fn fixture_tables_are_dropped_in_group() {
        // Success-path fixtures (fz_pg_* tables created OUTSIDE error
        // arms) all have an in-group DROP; error-arm creates (fz_pg_e*,
        // fz_pg_*_e*) never succeed so they need no drop.
        for group in gen_groups(41, 300) {
            let joined = group.join("\n");
            for sql in &group {
                let Some(rest) = sql.strip_prefix("CREATE TABLE ") else { continue };
                let t = rest.split_whitespace().next().unwrap().to_string();
                let base = t.clone();
                if base.contains("_e") || base.contains("fz_pg_ph_") || base.contains("fz_pg_pr_")
                    || base.contains("fz_pg_pl_") || base.contains("fz_pg_lk_c")
                    || base.contains("fz_pg_att")
                {
                    continue; // error arms / partition children / LIKE clones (bulk-dropped)
                }
                assert!(
                    joined.contains(&format!("DROP TABLE {base}"))
                        || joined.contains(&format!("{base},"))
                        || joined.contains(&format!(", {base}")),
                    "no in-group DROP for {base} in {group:?}"
                );
            }
        }
    }

    #[test]
    fn stream_is_seed_deterministic() {
        assert_eq!(gen_groups(5, 80), gen_groups(5, 80));
    }
}
