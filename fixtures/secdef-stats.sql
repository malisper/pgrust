CREATE FUNCTION secdef_inner() RETURNS int LANGUAGE plpgsql SECURITY DEFINER AS $$ BEGIN RETURN 7; END $$;
CREATE FUNCTION secdef_outer() RETURNS int LANGUAGE plpgsql SECURITY DEFINER AS $$ BEGIN RETURN secdef_inner(); END $$;
CREATE FUNCTION secdef_error() RETURNS int LANGUAGE plpgsql SECURITY DEFINER AS $$ BEGIN RAISE EXCEPTION 'expected'; END $$;
CREATE FUNCTION config_sql() RETURNS int LANGUAGE sql SET work_mem = '64MB' AS 'SELECT 42';
CREATE FUNCTION secdef_set() RETURNS SETOF int LANGUAGE plpgsql SECURITY DEFINER AS $$ BEGIN RETURN NEXT 1; RETURN NEXT 2; END $$;
BEGIN;
SET LOCAL track_functions = 'pl';
SELECT secdef_outer();
SELECT pg_stat_get_xact_function_calls('secdef_inner'::regproc), pg_stat_get_xact_function_calls('secdef_outer'::regproc);
SELECT config_sql();
SELECT pg_stat_get_xact_function_calls('config_sql'::regproc);
SET LOCAL track_functions = 'all';
SELECT config_sql();
SELECT pg_stat_get_xact_function_calls('config_sql'::regproc);
SAVEPOINT before_error;
SELECT secdef_error();
ROLLBACK TO before_error;
SELECT coalesce(pg_stat_get_xact_function_calls('secdef_error'::regproc), 0);
SELECT * FROM secdef_set();
SELECT pg_stat_get_xact_function_calls('secdef_set'::regproc);
SET LOCAL track_functions = 'none';
SELECT secdef_inner();
SELECT pg_stat_get_xact_function_calls('secdef_inner'::regproc);
COMMIT;
