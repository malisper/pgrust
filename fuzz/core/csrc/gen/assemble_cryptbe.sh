static _Thread_local int pg_cryptbe_logfired = 0;	/* LOG */
static _Thread_local int pg_cryptbe_pending = 0;

static int
pg_cryptbe_set_pending_code(int eclass)
{
	pg_cryptbe_pending = eclass;
	return 0;
}

static int
pg_cryptbe_pending_take(void)
{
	int			c = pg_cryptbe_pending;

	pg_cryptbe_pending = 0;
	return c;
}

static void
pg_cryptbe_report(int level, int eclass)
{
	if (level >= ERROR)
	{
		pg_cryptbe_errclass = eclass ? eclass : PG_CRYPTBE_ECLASS_INTERNAL;
		if (pg_cryptbe_armed)
			longjmp(pg_cryptbe_jmp, 1);
		abort();				/* wrapper forgot to arm — harness bug */
	}
	else if (level == WARNING)
		pg_cryptbe_warnclass = eclass ? eclass : PG_CRYPTBE_ECLASS_INTERNAL;
	else
		pg_cryptbe_logfired = 1;
}

#define errcode(c)				pg_cryptbe_set_pending_code(c)
#define errmsg(...)				0
#define errmsg_internal(...)	0
#define errdetail(...)			0
#define errhint(...)			0
#define ereport(level, rest) \
	do { (void) (rest); pg_cryptbe_report((level), pg_cryptbe_pending_take()); } while (0)
#define elog(level, ...) \
	pg_cryptbe_report((level), PG_CRYPTBE_ECLASS_INTERNAL)

/* ---------------- shim: per-exec pointer arena ---------------------------- */

#define PG_CRYPTBE_ARENA_MAX 512

static _Thread_local void *pg_cryptbe_arena[PG_CRYPTBE_ARENA_MAX];
static _Thread_local int pg_cryptbe_arena_n = 0;

static void *
pg_cryptbe_palloc(size_t size)
{
	void	   *p = malloc(size ? size : 1);

	if (p == NULL || pg_cryptbe_arena_n >= PG_CRYPTBE_ARENA_MAX)
		abort();				/* harness resource error, never a verdict */
	pg_cryptbe_arena[pg_cryptbe_arena_n++] = p;
	return p;
}

static char *
pg_cryptbe_pstrdup(const char *s)
{
	size_t		n = strlen(s) + 1;
	char	   *p = pg_cryptbe_palloc(n);

	memcpy(p, s, n);
	return p;
}

static char *
pg_cryptbe_psprintf(const char *fmt,...)
{
	va_list		ap;
	char		buf[1024];
	int			n;

	va_start(ap, fmt);
	n = vsnprintf(buf, sizeof(buf), fmt, ap);
	va_end(ap);
	if (n < 0 || n >= (int) sizeof(buf))
		abort();
	return pg_cryptbe_pstrdup(buf);
}

