void
pg_cryptbe_reset(void)
{
	for (int i = 0; i < pg_cryptbe_arena_n; i++)
		free(pg_cryptbe_arena[i]);
	pg_cryptbe_arena_n = 0;
	pg_cryptbe_errclass = 0;
