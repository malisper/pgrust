/*
 * Returns 0 and the NUL-terminated secret in out (cap bytes) on success;
 * -eclass on ereport(ERROR).
 */
int
pg_cryptbe_w_encrypt_password(int target_type, const char *role,
							  const char *password, char *out, size_t cap)
{
	char	   *r;

	pg_cryptbe_armed = 1;
	if (setjmp(pg_cryptbe_jmp))
	{
		pg_cryptbe_armed = 0;
		return -pg_cryptbe_errclass;
	}
	r = encrypt_password((PasswordType) target_type, role, password);
	pg_cryptbe_armed = 0;
	if (r == NULL || strlen(r) + 1 > cap)
		abort();				/* cap is a harness sizing bug, not a verdict */
	memcpy(out, r, strlen(r) + 1);
	return 0;
}

