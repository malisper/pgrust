static void
pg_instrbe_put8(unsigned char *p, uint64 v)
{
	int			i;

	for (i = 0; i < 8; i++)
		p[i] = (unsigned char) (v >> (8 * i));
}

static uint64
pg_instrbe_get8(const unsigned char *p)
{
	uint64		v = 0;
	int			i;

	for (i = 0; i < 8; i++)
		v |= (uint64) p[i] << (8 * i);
	return v;
}

static void
pg_instrbe_buf_pack(unsigned char *out, const BufferUsage *b)
{
	pg_instrbe_put8(out + 0, (uint64) b->shared_blks_hit);
	pg_instrbe_put8(out + 8, (uint64) b->shared_blks_read);
	pg_instrbe_put8(out + 16, (uint64) b->shared_blks_dirtied);
	pg_instrbe_put8(out + 24, (uint64) b->shared_blks_written);
	pg_instrbe_put8(out + 32, (uint64) b->local_blks_hit);
	pg_instrbe_put8(out + 40, (uint64) b->local_blks_read);
	pg_instrbe_put8(out + 48, (uint64) b->local_blks_dirtied);
	pg_instrbe_put8(out + 56, (uint64) b->local_blks_written);
	pg_instrbe_put8(out + 64, (uint64) b->temp_blks_read);
	pg_instrbe_put8(out + 72, (uint64) b->temp_blks_written);
	pg_instrbe_put8(out + 80, (uint64) b->shared_blk_read_time.ticks);
	pg_instrbe_put8(out + 88, (uint64) b->shared_blk_write_time.ticks);
	pg_instrbe_put8(out + 96, (uint64) b->local_blk_read_time.ticks);
	pg_instrbe_put8(out + 104, (uint64) b->local_blk_write_time.ticks);
	pg_instrbe_put8(out + 112, (uint64) b->temp_blk_read_time.ticks);
	pg_instrbe_put8(out + 120, (uint64) b->temp_blk_write_time.ticks);
}

static void
pg_instrbe_buf_unpack(BufferUsage *b, const unsigned char *in)
{
	b->shared_blks_hit = (int64) pg_instrbe_get8(in + 0);
	b->shared_blks_read = (int64) pg_instrbe_get8(in + 8);
	b->shared_blks_dirtied = (int64) pg_instrbe_get8(in + 16);
	b->shared_blks_written = (int64) pg_instrbe_get8(in + 24);
	b->local_blks_hit = (int64) pg_instrbe_get8(in + 32);
	b->local_blks_read = (int64) pg_instrbe_get8(in + 40);
	b->local_blks_dirtied = (int64) pg_instrbe_get8(in + 48);
	b->local_blks_written = (int64) pg_instrbe_get8(in + 56);
	b->temp_blks_read = (int64) pg_instrbe_get8(in + 64);
	b->temp_blks_written = (int64) pg_instrbe_get8(in + 72);
	b->shared_blk_read_time.ticks = (int64) pg_instrbe_get8(in + 80);
	b->shared_blk_write_time.ticks = (int64) pg_instrbe_get8(in + 88);
	b->local_blk_read_time.ticks = (int64) pg_instrbe_get8(in + 96);
	b->local_blk_write_time.ticks = (int64) pg_instrbe_get8(in + 104);
	b->temp_blk_read_time.ticks = (int64) pg_instrbe_get8(in + 112);
	b->temp_blk_write_time.ticks = (int64) pg_instrbe_get8(in + 120);
}

static void
pg_instrbe_wal_pack(unsigned char *out, const WalUsage *w)
{
	pg_instrbe_put8(out + 0, (uint64) w->wal_records);
	pg_instrbe_put8(out + 8, (uint64) w->wal_fpi);
	pg_instrbe_put8(out + 16, w->wal_bytes);
	pg_instrbe_put8(out + 24, (uint64) w->wal_buffers_full);
}

static void
pg_instrbe_wal_unpack(WalUsage *w, const unsigned char *in)
{
	w->wal_records = (int64) pg_instrbe_get8(in + 0);
	w->wal_fpi = (int64) pg_instrbe_get8(in + 8);
	w->wal_bytes = pg_instrbe_get8(in + 16);
	w->wal_buffers_full = (int64) pg_instrbe_get8(in + 24);
}

static double
pg_instrbe_bits_to_double(uint64 bits)
{
	double		d;

	memcpy(&d, &bits, 8);
	return d;
}

static uint64
pg_instrbe_double_to_bits(double d)
{
	uint64		bits;

	memcpy(&bits, &d, 8);
	return bits;
}

static void
pg_instrbe_instr_pack(unsigned char *out, const Instrumentation *n)
{
	out[0] = n->need_timer ? 1 : 0;
	out[1] = n->need_bufusage ? 1 : 0;
	out[2] = n->need_walusage ? 1 : 0;
	out[3] = n->async_mode ? 1 : 0;
	out[4] = n->running ? 1 : 0;
	pg_instrbe_put8(out + 5, (uint64) n->starttime.ticks);
	pg_instrbe_put8(out + 13, (uint64) n->counter.ticks);
	pg_instrbe_put8(out + 21, pg_instrbe_double_to_bits(n->firsttuple));
	pg_instrbe_put8(out + 29, pg_instrbe_double_to_bits(n->tuplecount));
	pg_instrbe_buf_pack(out + 37, &n->bufusage_start);
	pg_instrbe_wal_pack(out + 165, &n->walusage_start);
	pg_instrbe_put8(out + 197, pg_instrbe_double_to_bits(n->startup));
	pg_instrbe_put8(out + 205, pg_instrbe_double_to_bits(n->total));
	pg_instrbe_put8(out + 213, pg_instrbe_double_to_bits(n->ntuples));
	pg_instrbe_put8(out + 221, pg_instrbe_double_to_bits(n->ntuples2));
	pg_instrbe_put8(out + 229, pg_instrbe_double_to_bits(n->nloops));
	pg_instrbe_put8(out + 237, pg_instrbe_double_to_bits(n->nfiltered1));
	pg_instrbe_put8(out + 245, pg_instrbe_double_to_bits(n->nfiltered2));
	pg_instrbe_buf_pack(out + 253, &n->bufusage);
	pg_instrbe_wal_pack(out + 381, &n->walusage);
}

static void
pg_instrbe_instr_unpack(Instrumentation *n, const unsigned char *in)
{
	n->need_timer = (in[0] != 0);
	n->need_bufusage = (in[1] != 0);
	n->need_walusage = (in[2] != 0);
	n->async_mode = (in[3] != 0);
	n->running = (in[4] != 0);
	n->starttime.ticks = (int64) pg_instrbe_get8(in + 5);
	n->counter.ticks = (int64) pg_instrbe_get8(in + 13);
	n->firsttuple = pg_instrbe_bits_to_double(pg_instrbe_get8(in + 21));
	n->tuplecount = pg_instrbe_bits_to_double(pg_instrbe_get8(in + 29));
	pg_instrbe_buf_unpack(&n->bufusage_start, in + 37);
	pg_instrbe_wal_unpack(&n->walusage_start, in + 165);
	n->startup = pg_instrbe_bits_to_double(pg_instrbe_get8(in + 197));
	n->total = pg_instrbe_bits_to_double(pg_instrbe_get8(in + 205));
	n->ntuples = pg_instrbe_bits_to_double(pg_instrbe_get8(in + 213));
	n->ntuples2 = pg_instrbe_bits_to_double(pg_instrbe_get8(in + 221));
	n->nloops = pg_instrbe_bits_to_double(pg_instrbe_get8(in + 229));
	n->nfiltered1 = pg_instrbe_bits_to_double(pg_instrbe_get8(in + 237));
	n->nfiltered2 = pg_instrbe_bits_to_double(pg_instrbe_get8(in + 245));
	pg_instrbe_buf_unpack(&n->bufusage, in + 253);
	pg_instrbe_wal_unpack(&n->walusage, in + 381);
}

/* Two node slots: 0 = the working node (dst), 1 = the AggNode add-side. */
static _Thread_local Instrumentation pg_instrbe_nodes[2];

/* Zero the nodes AND the globals: the pgBufferUsage zero-pin of record
 * (see file header); pgWalUsage starts zero and is advanced only by
 * pg_instrbe_set_wal_global (mirrored by the Rust seam pin). */
void
pg_instrbe_reset(void)
{
	memset(&pg_instrbe_nodes[0], 0, sizeof(Instrumentation));
	memset(&pg_instrbe_nodes[1], 0, sizeof(Instrumentation));
	memset(&pgBufferUsage, 0, sizeof(BufferUsage));
	memset(&pgWalUsage, 0, sizeof(WalUsage));
	pg_instrbe_errmsg_v = "";
}

/* stub wal-global: fuzz-fed pgWalUsage, identical on the Rust side via the
 * installed transam_xlog_seams::wal_usage seam. */
void
pg_instrbe_set_wal_global(const unsigned char *w)
{
	pg_instrbe_wal_unpack(&pgWalUsage, w);
}

/* async_mode is set by InstrAlloc in C (census OUT); the driver sets the
 * field directly on both sides. */
void
pg_instrbe_set_async(int on)
{
	pg_instrbe_nodes[0].async_mode = (on != 0);
}

void
pg_instrbe_load_node(int which, const unsigned char *wire)
{
	pg_instrbe_instr_unpack(&pg_instrbe_nodes[which & 1], wire);
}

void
pg_instrbe_store_node(int which, unsigned char *out)
{
	pg_instrbe_instr_pack(out, &pg_instrbe_nodes[which & 1]);
}

const char *
pg_instrbe_errmsg(void)
{
	return pg_instrbe_errmsg_v;
}

void
pg_instrbe_init(int options)
{
	InstrInit(&pg_instrbe_nodes[0], options);
}

/* 0 = ok, 1 = elog'ed (literal in pg_instrbe_errmsg). State mutations made
 * before the elog persist, exactly as they do across the Rust panic. */
int
pg_instrbe_start_node(void)
{
	if (setjmp(pg_instrbe_jmp))
		return 1;
	InstrStartNode(&pg_instrbe_nodes[0]);
	return 0;
}

int
pg_instrbe_stop_node(uint64 ntuples_bits)
{
	if (setjmp(pg_instrbe_jmp))
		return 1;
	InstrStopNode(&pg_instrbe_nodes[0], pg_instrbe_bits_to_double(ntuples_bits));
	return 0;
}

void
pg_instrbe_update_tuple_count(uint64 ntuples_bits)
