	InstrUpdateTupleCount(&pg_instrbe_nodes[0],
						  pg_instrbe_bits_to_double(ntuples_bits));
}

int
pg_instrbe_end_loop(int which)
{
	if (setjmp(pg_instrbe_jmp))
		return 1;
	InstrEndLoop(&pg_instrbe_nodes[which & 1]);
	return 0;
}

void
pg_instrbe_agg_node(void)
{
	InstrAggNode(&pg_instrbe_nodes[0], &pg_instrbe_nodes[1]);
}

/* Pure struct arithmetic, wire in / wire out. */
void
pg_instrbe_bufusage_add(unsigned char *dst, const unsigned char *add)
{
	BufferUsage d,
				a;

	pg_instrbe_buf_unpack(&d, dst);
	pg_instrbe_buf_unpack(&a, add);
	BufferUsageAdd(&d, &a);
	pg_instrbe_buf_pack(dst, &d);
}

void
pg_instrbe_bufusage_accum_diff(unsigned char *dst, const unsigned char *add,
							   const unsigned char *sub)
{
	BufferUsage d,
				a,
				s;

	pg_instrbe_buf_unpack(&d, dst);
	pg_instrbe_buf_unpack(&a, add);
	pg_instrbe_buf_unpack(&s, sub);
	BufferUsageAccumDiff(&d, &a, &s);
	pg_instrbe_buf_pack(dst, &d);
}

void
pg_instrbe_walusage_add(unsigned char *dst, const unsigned char *add)
{
	WalUsage	d,
				a;

	pg_instrbe_wal_unpack(&d, dst);
	pg_instrbe_wal_unpack(&a, add);
	WalUsageAdd(&d, &a);
	pg_instrbe_wal_pack(dst, &d);
}

void
pg_instrbe_walusage_accum_diff(unsigned char *dst, const unsigned char *add,
							   const unsigned char *sub)
{
	WalUsage	d,
				a,
				s;

	pg_instrbe_wal_unpack(&d, dst);
	pg_instrbe_wal_unpack(&a, add);
	pg_instrbe_wal_unpack(&s, sub);
	WalUsageAccumDiff(&d, &a, &s);
	pg_instrbe_wal_pack(dst, &d);
}

